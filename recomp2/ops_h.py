"""recomp_ops.h: the helpers the generated C uses (prefix r2_).

Written from the ARM Architecture Reference Manual (ARM DDI 0100I):
A5.1 (shifter operands and their carry-out), A4.1.2/A4.1.3/A4.1.106 etc.
(flag rules of ADD/ADC/SUB/SBC: C = carry out / NOT borrow, V = signed
overflow), A4.1.23 (LDR rotates a word read from an unaligned address),
A10 (saturating arithmetic and the sticky Q flag). Only fixed-width unsigned
arithmetic: no undefined or implementation-specific behaviour beyond two's
complement conversions, so every compiler computes the same values.

The header is included after cpu.h (and after the ARM7 renaming defines), so
its memory accesses go to the right CPU.
"""

TEXT = r"""/* Helpers for the recompiled code (generated by recomp2/ops_h.py). */
#pragma once
#include <stdint.h>

static inline uint32_t r2_ror(uint32_t v, uint32_t n) { n &= 31u; return n ? (v >> n) | (v << (32u - n)) : v; }

/* Word load: an unaligned address reads the aligned word rotated right by 8 * (addr & 3). */
static inline uint32_t r2_ldr32(uint32_t a) { return r2_ror(mem_read32(a & ~3u), (a & 3u) * 8u); }
static inline uint32_t r2_sx8(uint32_t v) { return (v & 0x80u) ? (v | 0xFFFFFF00u) : (v & 0xFFu); }
static inline uint32_t r2_sx16(uint32_t v) { return (v & 0x8000u) ? (v | 0xFFFF0000u) : (v & 0xFFFFu); }

/* Flags. */
static inline uint32_t r2_nz(Cpu* c, uint32_t r) { c->n = r >> 31; c->z = (r == 0); return r; }
static inline uint32_t r2_adds(Cpu* c, uint32_t a, uint32_t b) {
    uint32_t r = a + b;
    c->n = r >> 31; c->z = (r == 0); c->cf = (r < a); c->v = ((a ^ r) & (b ^ r)) >> 31;
    return r;
}
static inline uint32_t r2_adcs(Cpu* c, uint32_t a, uint32_t b, uint32_t cin) {
    uint64_t w = (uint64_t)a + (uint64_t)b + (uint64_t)cin;
    uint32_t r = (uint32_t)w;
    c->n = r >> 31; c->z = (r == 0); c->cf = (uint32_t)(w >> 32); c->v = ((a ^ r) & (b ^ r)) >> 31;
    return r;
}
static inline uint32_t r2_subs(Cpu* c, uint32_t a, uint32_t b) {
    uint32_t r = a - b;
    c->n = r >> 31; c->z = (r == 0); c->cf = (a >= b); c->v = ((a ^ b) & (a ^ r)) >> 31;
    return r;
}
static inline uint32_t r2_sbcs(Cpu* c, uint32_t a, uint32_t b, uint32_t cin) {
    uint64_t sub = (uint64_t)b + (uint64_t)(1u - cin);
    uint32_t r = a - b - (1u - cin);
    c->n = r >> 31; c->z = (r == 0); c->cf = ((uint64_t)a >= sub); c->v = ((a ^ b) & (a ^ r)) >> 31;
    return r;
}

/* Immediate shifts (amount 1..31, or 32 for LSR/ASR), with carry-out. */
static inline uint32_t r2_lsl_ic(uint32_t v, uint32_t n, uint32_t* co) { *co = (v >> (32u - n)) & 1u; return v << n; }
static inline uint32_t r2_lsr_ic(uint32_t v, uint32_t n, uint32_t* co) {
    if (n >= 32u) { *co = v >> 31; return 0; }
    *co = (v >> (n - 1u)) & 1u; return v >> n;
}
static inline uint32_t r2_asr_i(uint32_t v, uint32_t n) {
    if (n >= 32u) return (v & 0x80000000u) ? 0xFFFFFFFFu : 0u;
    return (v & 0x80000000u) ? ((v >> n) | ~(0xFFFFFFFFu >> n)) : (v >> n);
}
static inline uint32_t r2_asr_ic(uint32_t v, uint32_t n, uint32_t* co) {
    *co = (n >= 32u) ? (v >> 31) : ((v >> (n - 1u)) & 1u); return r2_asr_i(v, n);
}
static inline uint32_t r2_ror_ic(uint32_t v, uint32_t n, uint32_t* co) { *co = (v >> (n - 1u)) & 1u; return r2_ror(v, n); }

/* Register-specified shifts: the amount is the bottom byte of Rs (A5.1.6, A5.1.8, A5.1.10, A5.1.12).
 * The carry pointer holds the carry in and receives the carry out. */
static inline uint32_t r2_lsl_r(uint32_t v, uint32_t s, uint32_t* co) {
    s &= 0xFFu;
    if (s == 0) return v;
    if (s < 32u) { *co = (v >> (32u - s)) & 1u; return v << s; }
    *co = (s == 32u) ? (v & 1u) : 0u; return 0;
}
static inline uint32_t r2_lsr_r(uint32_t v, uint32_t s, uint32_t* co) {
    s &= 0xFFu;
    if (s == 0) return v;
    if (s < 32u) { *co = (v >> (s - 1u)) & 1u; return v >> s; }
    *co = (s == 32u) ? (v >> 31) : 0u; return 0;
}
static inline uint32_t r2_asr_r(uint32_t v, uint32_t s, uint32_t* co) {
    s &= 0xFFu;
    if (s == 0) return v;
    if (s < 32u) { *co = (v >> (s - 1u)) & 1u; return r2_asr_i(v, s); }
    *co = v >> 31; return r2_asr_i(v, 32u);
}
static inline uint32_t r2_ror_r(uint32_t v, uint32_t s, uint32_t* co) {
    s &= 0xFFu;
    if (s == 0) return v;
    if ((s & 31u) == 0) { *co = v >> 31; return v; }
    *co = (v >> ((s & 31u) - 1u)) & 1u; return r2_ror(v, s & 31u);
}

/* Multiplies. */
static inline uint64_t r2_smull(uint32_t a, uint32_t b) {
    return (uint64_t)((int64_t)(int32_t)a * (int64_t)(int32_t)b);
}
static inline uint32_t r2_half(uint32_t v, int top) { return r2_sx16(top ? (v >> 16) : (v & 0xFFFFu)); }
/* SMULW: bits 47..16 of the 48-bit product of Rm and a signed half of Rs. */
static inline uint32_t r2_smulw(uint32_t a, uint32_t h) { return (uint32_t)(r2_smull(a, h) >> 16); }

/* Saturation (A10): the sticky Q flag is set, never cleared here. */
static inline uint32_t r2_sat(Cpu* c, int64_t r) {
    if (r > 0x7FFFFFFFLL) { c->q = 1; return 0x7FFFFFFFu; }
    if (r < -0x80000000LL) { c->q = 1; return 0x80000000u; }
    return (uint32_t)r;
}
static inline int64_t r2_s64(uint32_t v) { return (int64_t)(int32_t)v; }
static inline uint32_t r2_qadd(Cpu* c, uint32_t a, uint32_t b) { return r2_sat(c, r2_s64(a) + r2_s64(b)); }
static inline uint32_t r2_qsub(Cpu* c, uint32_t a, uint32_t b) { return r2_sat(c, r2_s64(a) - r2_s64(b)); }
static inline uint32_t r2_qdouble(Cpu* c, uint32_t a) { return r2_sat(c, r2_s64(a) * 2); }
/* Addition that only sets Q on signed overflow (SMLAxy, SMLAWy). */
static inline uint32_t r2_addq(Cpu* c, uint32_t a, uint32_t b) {
    uint32_t r = a + b;
    if (((a ^ r) & (b ^ r)) >> 31) c->q = 1;
    return r;
}

static inline uint32_t r2_clz(uint32_t v) {
    uint32_t n = 0;
    if (!v) return 32;
    while (!(v & 0x80000000u)) { v <<= 1; n++; }
    return n;
}
"""
